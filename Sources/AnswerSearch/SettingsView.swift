import AnswerSearchKit
import SwiftUI

struct SettingsView: View {
    @ObservedObject var viewModel: SettingsViewModel
    let onDone: () -> Void
    let onLaunch: () -> Void
    @State private var showsDeleteAPIKeyConfirmation = false
    @State private var showsDeleteAllConfirmation = false

    var body: some View {
        VStack(spacing: 0) {
            ScrollView {
                VStack(alignment: .leading, spacing: 18) {
                    header
                    if viewModel.needsSetup {
                        setupNotice
                    }
                    form
                }
                .padding(24)
            }

            Divider()
            footer
                .padding(.horizontal, 24)
                .padding(.vertical, 12)
        }
        .frame(width: 620)
    }

    private var header: some View {
        HStack(alignment: .firstTextBaseline) {
            Text(viewModel.title)
                .font(.largeTitle.weight(.semibold))
            Spacer()
            Button("Done", action: onDone)
                .keyboardShortcut(.cancelAction)
        }
    }

    private var setupNotice: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text("AnswerSearch sends your questions to the AI provider you choose, using your own API key. The key is stored in your macOS Keychain and is only ever sent to that provider.")
            Text("Answers are generated by AI and can be inaccurate. Check anything important.")
        }
        .font(.body)
        .foregroundStyle(.secondary)
        .padding(12)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Color(nsColor: .controlBackgroundColor))
        .clipShape(RoundedRectangle(cornerRadius: 8))
    }

    private var form: some View {
        VStack(alignment: .leading, spacing: 18) {
            if !viewModel.providerAnswersAvailable {
                osNotice
            }
            providerSection
            credentialSection
            providerConfigSection
            localAISection
            answerModeSection
            startupSection
            keyboardShortcutSection
            localResultsSection
            actions
            status
        }
        .font(.body)
        .disabled(viewModel.isSaving)
    }

    private var providerSection: some View {
        SettingsRow(label: "AI provider") {
            Picker("", selection: $viewModel.provider) {
                ForEach(viewModel.providerOptions) { provider in
                    Text(provider.displayName).tag(provider)
                }
            }
            .pickerStyle(.menu)
            .labelsHidden()
            .frame(maxWidth: .infinity, alignment: .leading)
            .onChange(of: viewModel.provider) {
                viewModel.providerDidChange()
            }
        }
    }

    private var credentialSection: some View {
        VStack(alignment: .leading, spacing: 8) {
            SettingsRow(label: viewModel.provider.apiKeyLabel) {
                SecureField(viewModel.apiKeyPlaceholder, text: $viewModel.apiKey)
                    .textFieldStyle(.roundedBorder)
            }
            Button("Show me how to get an API key") {
                viewModel.openLink(viewModel.provider.apiKeyHelpURL)
            }
            .buttonStyle(.link)
            if viewModel.isReadyToLaunch {
                Button("Launch AnswerSearch") {
                    viewModel.markAnswerSearchLaunched()
                    onLaunch()
                }
                .keyboardShortcut(.defaultAction)
            } else {
                Button("Save AI provider") {
                    viewModel.saveCredentialSection()
                }
                .disabled(!viewModel.canSaveCredentialSection)
            }
        }
    }

    private var answerModeSection: some View {
        SettingsSection(title: "Answer Mode") {
            Picker("", selection: $viewModel.responseMode) {
                ForEach(viewModel.responseModeOptions, id: \.self) { mode in
                    Text(mode.label).tag(mode)
                }
            }
            .pickerStyle(.segmented)
            .labelsHidden()
            .onChange(of: viewModel.responseMode) {
                viewModel.responseModeDidChange()
            }
            Text(viewModel.responseMode.help)
                .font(.caption)
                .foregroundStyle(.secondary)
        }
    }

    private var osNotice: some View {
        Text("Claude and OpenAI answers need macOS 27 or later. On this Mac only Local AI (Apple Intelligence) is available.")
            .font(.callout)
            .foregroundStyle(.secondary)
            .padding(12)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(Color(nsColor: .controlBackgroundColor))
            .clipShape(RoundedRectangle(cornerRadius: 8))
    }

    private var providerConfigSection: some View {
        VStack(alignment: .leading, spacing: 10) {
            SettingsRow(label: "Model") {
                HStack {
                    TextField(viewModel.provider.modelPlaceholder, text: $viewModel.model)
                        .textFieldStyle(.roundedBorder)
                }
            }
        }
    }

    private var localAISection: some View {
        SettingsSection(title: "Local AI (Experimental)") {
            VStack(alignment: .leading, spacing: 6) {
                Toggle("Enable Local AI Answer Mode", isOn: $viewModel.automaticallyUseLocalAI)
                    .disabled(!viewModel.localAIAvailable)
                    .onChange(of: viewModel.automaticallyUseLocalAI) {
                        viewModel.localAISettingDidChange()
                    }
                Text(viewModel.localAIStatusText)
                    .font(.caption)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
    }

    private var startupSection: some View {
        SettingsSection(title: "Startup") {
            VStack(alignment: .leading, spacing: 6) {
                Toggle("Start AnswerSearch when I sign in", isOn: $viewModel.startAtSignIn)
                    .onChange(of: viewModel.startAtSignIn) {
                        viewModel.startAtSignInDidChange()
                    }
                Text("Open AnswerSearch automatically after you sign in to this Mac.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
            }
        }
    }

    private var keyboardShortcutSection: some View {
        SettingsSection(title: "Keyboard Shortcut") {
            VStack(alignment: .leading, spacing: 10) {
                Toggle("Open AnswerSearch with a keyboard shortcut", isOn: $viewModel.keyboardShortcutEnabled)
                    .onChange(of: viewModel.keyboardShortcutEnabled) {
                        viewModel.keyboardShortcutDidChange()
                    }
                HStack(alignment: .bottom, spacing: 12) {
                    SettingsRow(label: "Shortcut") {
                        Picker("", selection: $viewModel.keyboardShortcutModifiers) {
                            Text("Control + Option").tag("control+option")
                            Text("Control + Shift").tag("control+shift")
                            Text("Option + Shift").tag("option+shift")
                        }
                        .labelsHidden()
                        .onChange(of: viewModel.keyboardShortcutModifiers) {
                            viewModel.keyboardShortcutDidChange()
                        }
                    }
                    SettingsRow(label: "Key") {
                        Picker("", selection: $viewModel.keyboardShortcutKey) {
                            Text("Space").tag("space")
                            Text("Return").tag("return")
                            Text("F").tag("f")
                            Text("K").tag("k")
                        }
                        .labelsHidden()
                        .onChange(of: viewModel.keyboardShortcutKey) {
                            viewModel.keyboardShortcutDidChange()
                        }
                    }
                    Button("Reset to Suggested Shortcut") {
                        viewModel.resetShortcut()
                    }
                }
            }
        }
    }

    private var localResultsSection: some View {
        SettingsSection(title: "Local Results") {
            VStack(alignment: .leading, spacing: 10) {
                Text("Optional. Shared with your AI provider only when a question uses web search, to make results more relevant to where you are.")
                    .font(.body)
                    .foregroundStyle(.secondary)
                HStack(spacing: 12) {
                    LabeledTextField("City", text: $viewModel.userCity)
                    LabeledTextField("Region", text: $viewModel.userRegion)
                }
                HStack(spacing: 12) {
                    LabeledTextField("Country", text: $viewModel.userCountry, prompt: "United States")
                    LabeledTextField("Timezone", text: $viewModel.userTimezone)
                }
            }
        }
    }

    private var actions: some View {
        HStack {
            if viewModel.isReadyToLaunch {
                Button("Launch AnswerSearch") {
                    viewModel.markAnswerSearchLaunched()
                    onLaunch()
                }
                .keyboardShortcut(.defaultAction)
            } else {
                Button("Save") {
                    viewModel.save()
                }
            }
            Button("Done", action: onDone)
            Spacer()
            Button("Delete API key", role: .destructive) {
                showsDeleteAPIKeyConfirmation = true
            }
            Button("Delete local data", role: .destructive) {
                showsDeleteAllConfirmation = true
            }
        }
        .confirmationDialog(
            "Delete the stored API key?",
            isPresented: $showsDeleteAPIKeyConfirmation
        ) {
            Button("Delete API key", role: .destructive) {
                viewModel.deleteAPIKey()
            }
            Button("Cancel", role: .cancel) {}
        }
        .confirmationDialog(
            "Delete the API key and local AnswerSearch settings? Search history is not stored.",
            isPresented: $showsDeleteAllConfirmation
        ) {
            Button("Delete local data", role: .destructive) {
                viewModel.deleteAll()
            }
            Button("Cancel", role: .cancel) {}
        }
    }

    @ViewBuilder
    private var status: some View {
        if viewModel.isSaving {
            ProgressView("Saving...")
        } else if !viewModel.statusMessage.isEmpty {
            Text(viewModel.statusMessage)
                .font(.body)
                .foregroundStyle(viewModel.isErrorStatus ? .red : .secondary)
        }
    }

    private var footer: some View {
        HStack(spacing: 10) {
            Text(viewModel.versionText)
            Text("Apache License 2.0")
            Spacer()
            Button("About") {
                viewModel.openLink(AppLinks.project)
            }
            .buttonStyle(.link)
            Button("Privacy") {
                viewModel.openLink(AppLinks.privacy)
            }
            .buttonStyle(.link)
            Button("Report an issue") {
                viewModel.openLink(AppLinks.issues)
            }
            .buttonStyle(.link)
        }
        .font(.caption)
        .foregroundStyle(.secondary)
    }
}

private struct SettingsSection<Content: View>: View {
    let title: String
    @ViewBuilder let content: Content

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            Text(title)
                .font(.title3.weight(.semibold))
            content
        }
        .frame(maxWidth: .infinity, alignment: .leading)
    }
}

private struct SettingsRow<Content: View>: View {
    let label: String
    @ViewBuilder let content: Content

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(label)
                .font(.body.weight(.medium))
            content
        }
    }
}

private struct LabeledTextField: View {
    let label: String
    @Binding var text: String
    var prompt: String = ""

    init(_ label: String, text: Binding<String>, prompt: String = "") {
        self.label = label
        self._text = text
        self.prompt = prompt
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(label)
                .font(.body.weight(.medium))
            TextField(prompt, text: $text)
                .textFieldStyle(.roundedBorder)
        }
    }
}
